const puppeteer = require('puppeteer')
;(async () => {
  const browser = await puppeteer.launch({ headless: 'new' })
  const page = await browser.newPage()
  await page.setViewport({ width: 375, height: 900 })
  await page.goto('https://jayshop-retail-platform.vercel.app/shop/men-s-nike-toronto-blue-jays-guerrero-road-limited-jersey', { waitUntil: 'domcontentloaded', timeout: 60000 })
  await new Promise(r => setTimeout(r, 2000))
  const btns = await page.evaluate(() => Array.from(document.querySelectorAll('button')).map(b => b.getAttribute('aria-label')))
  console.log(JSON.stringify(btns))
  const bodyLen = await page.evaluate(() => document.body.innerText.slice(0, 300))
  console.log(bodyLen)
  await browser.close()
})()
